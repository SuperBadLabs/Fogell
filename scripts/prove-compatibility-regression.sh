baseline_for_corpus "$CASE_BASELINE" "$OUT/corpus-schema-baseline.json" "$CASE/corpus/CORPUS-SHA256SUMS"
expect_reject 'corpus manifest malformed row' "$CASE" "$OUT/corpus-schema-baseline.json" "$CASE_ORACLE" 'corpus manifest row violates the exact schema'

