#!/usr/bin/env bash
# FG-094. Offline proof for set-based compatibility non-regression.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
ROOT=$PWD
CHECKER="$ROOT/scripts/check-compatibility-regression.py"
if [ ! -f "$CHECKER" ] || [ ! -x "$CHECKER" ] || [ -L "$CHECKER" ]; then
  echo 'FG-094 proof REFUSED: repository checker is not an executable non-symlink file' >&2
  exit 1
fi

LAB=$(mktemp -d /tmp/fogell-fg094-proof.XXXXXX)
trap 'rm -rf "$LAB"' EXIT
REPO="$LAB/repo"
MOUNT="$LAB/mounted-corpus"
OUT="$LAB/output"
ORACLE="$OUT/oracle.tsv"
BASELINE="$OUT/baseline.json"
SCORECARD_MARKER="$OUT/scorecard-ran"
FAILED=0
mkdir -p "$REPO/scripts" "$REPO/docs" "$REPO/corpus" "$MOUNT" "$OUT"

sha256() { sha256sum "$1" | awk '{print $1}'; }

ledger_row() {
  local file=$1 tier=$2
  case "$tier" in
    1) printf '%s\t1\t-\treceipt:%s\n' "$file" "${file%.Jenkinsfile}" ;;
    admitted) printf '%s\tadmitted\t-\tparsed only\n' "$file" ;;
    3) printf '%s\t3\tmalformed_syntax\trefused at 1:1\n' "$file" ;;
    *) echo "bad proof tier: $tier" >&2; exit 2 ;;
  esac
}

write_ledger() {
  local path=$1 notready=$2 ready=$3 tierone=$4 vins=$5
  {
    printf '%s\n' \
      '# Compatibility ledger — generated by proof' \
      '# tier 1 = proven compatible' \
      '# admitted = parses only' \
      '# tier 3 = named refusal'
    printf 'file\ttier\tcode\tevidence\n'
    ledger_row notready.Jenkinsfile "$notready"
    ledger_row ready.Jenkinsfile "$ready"
    ledger_row tierone.Jenkinsfile "$tierone"
    ledger_row vinsguru_jenkins-pipeline.Jenkinsfile "$vins"
  } > "$path"
}

write_manifest() {
  local path=$1
  {
    printf '%064d  notready.Jenkinsfile\n' 0
    printf '%064d  ready.Jenkinsfile\n' 1
    printf '%064d  tierone.Jenkinsfile\n' 2
    printf '%064d  vinsguru_jenkins-pipeline.Jenkinsfile\n' 3
  } > "$path"
}

oracle_row() {
  local file=$1 compiled=$2 reached=$3
  printf '%s\tfixture/repo\t0\t1\tnot_declarative_pipeline\tfixture\tfixture\t1.0\t%s\t%s\tparsed\t0\t0\trejected\t0\t-\r\n' \
    "$file" "$compiled" "$reached"
}

write_oracle() {
  local path=$1
  {
    printf 'file\trepo\tstars\tbytes\tjenkins_lint\tjenkins_job_raw\tjenkins_job\tjenkins_elapsed_ms\tjenkins_compiled\tjenkins_reached_agent\tchengis\tchengis_stages\tchengis_steps\tranvil\tranvil_actions\tranvil_errors\r\n'
    oracle_row vinsguru_jenkins-pipeline.Jenkinsfile True False
    oracle_row notready.Jenkinsfile False False
    oracle_row ready.Jenkinsfile True True
    oracle_row tierone.Jenkinsfile False False
  } > "$path"
}

write_baseline() {
  local path=$1 repo=$2 commit=$3 oracle=$4 count=${5:-4} compiled=${6:-2} reached=${7:-1}
  local tree ledger_sha corpus_sha oracle_sha
  tree=$(git -C "$repo" rev-parse "$commit^{tree}")
  ledger_sha=$(git -C "$repo" show "$commit:docs/COMPATIBILITY-LEDGER.tsv" | sha256sum | awk '{print $1}')
  corpus_sha=$(sha256 "$repo/corpus/CORPUS-SHA256SUMS")
  oracle_sha=$(sha256 "$oracle")
  printf '{"schema_version":1,"baseline_commit":"%s","baseline_tree":"%s","baseline_ledger_sha256":"%s","corpus_manifest_sha256":"%s","corpus_file_count":%s,"jenkins_core":"2.568.1","jenkins_oracle_sha256":"%s","jenkins_compiled_count":%s,"jenkins_reached_agent_count":%s}\n' \
    "$commit" "$tree" "$ledger_sha" "$corpus_sha" "$count" "$oracle_sha" "$compiled" "$reached" > "$path"
}

baseline_for_oracle() {
  local source=$1 output=$2 oracle=$3 compiled=${4:-2} reached=${5:-1}
  local digest
  digest=$(sha256 "$oracle")
  sed -e "s/\"jenkins_oracle_sha256\":\"[0-9a-f]*\"/\"jenkins_oracle_sha256\":\"$digest\"/" \
      -e "s/\"jenkins_compiled_count\":[0-9]*/\"jenkins_compiled_count\":$compiled/" \
      -e "s/\"jenkins_reached_agent_count\":[0-9]*/\"jenkins_reached_agent_count\":$reached/" \
      "$source" > "$output"
}

baseline_for_corpus() {
  local source=$1 output=$2 manifest=$3 count=${4:-4}
  local digest
  digest=$(sha256 "$manifest")
  sed -e "s/\"corpus_manifest_sha256\":\"[0-9a-f]*\"/\"corpus_manifest_sha256\":\"$digest\"/" \
      -e "s/\"corpus_file_count\":[0-9]*/\"corpus_file_count\":$count/" \
      "$source" > "$output"
}

cp -p "$CHECKER" "$REPO/scripts/check-compatibility-regression.py"
printf '#!/bin/sh\nprintf "ran\\n" >> "%s"\n[ ! -e "%s" ]\n' "$SCORECARD_MARKER" "$OUT/scorecard-refuse" > "$REPO/scripts/generate-scorecard.bb"
chmod +x "$REPO/scripts/generate-scorecard.bb"
write_ledger "$REPO/docs/COMPATIBILITY-LEDGER.tsv" 3 admitted 1 admitted
write_manifest "$REPO/corpus/CORPUS-SHA256SUMS"
git -C "$REPO" init -q
git -C "$REPO" config user.name fogell-proof
git -C "$REPO" config user.email fogell-proof@example.invalid
git -C "$REPO" add scripts docs corpus
git -C "$REPO" commit -q -m baseline
BASE_COMMIT=$(git -C "$REPO" rev-parse HEAD)
write_oracle "$ORACLE"
write_baseline "$BASELINE" "$REPO" "$BASE_COMMIT" "$ORACLE"
printf 'candidate\n' > "$REPO/candidate.txt"
git -C "$REPO" add candidate.txt
git -C "$REPO" commit -q -m candidate

run_gate() {
  local repo=$1 baseline=$2 oracle=$3 log=$4
  shift 4
  set +e
  env FOGELL_CORPUS="$MOUNT" FOGELL_REGRESSION_BASELINE="$baseline" FOGELL_JENKINS_ORACLE="$oracle" "$@" \
    "$repo/scripts/check-compatibility-regression.py" > "$log" 2>&1
  RC=$?
  set -e
}

expect_pass() {
  local label=$1 repo=$2 baseline=$3 oracle=$4
  shift 4
  rm -f "$SCORECARD_MARKER"
  run_gate "$repo" "$baseline" "$oracle" "$OUT/run.log" "$@"
  if [ "$RC" -ne 0 ] || ! grep -Fq 'FG-094 COMPATIBILITY REGRESSION GATE PASSED:' "$OUT/run.log" || [ ! -f "$SCORECARD_MARKER" ]; then
    echo "  FAIL: $label did not pass after scorecard check"
    sed 's/^/    | /' "$OUT/run.log"
    FAILED=1
  else
    echo "  passed $label"
  fi
}

expect_reject() {
  local label=$1 repo=$2 baseline=$3 oracle=$4 wanted=$5
  shift 5
  rm -f "$SCORECARD_MARKER"
  run_gate "$repo" "$baseline" "$oracle" "$OUT/run.log" "$@"
  if [ "$RC" -eq 0 ] || ! grep -Fq "$wanted" "$OUT/run.log"; then
    echo "  FAIL: $label was not refused for: $wanted"
    sed 's/^/    | /' "$OUT/run.log"
    FAILED=1
  else
    echo "  rejected $label"
  fi
}

clone_case() {
  CASE="$LAB/case-$1"
  git clone -q "$REPO" "$CASE"
  git -C "$CASE" config user.name fogell-proof
  git -C "$CASE" config user.email fogell-proof@example.invalid
  CASE_BASELINE="$OUT/case-$1-baseline.json"
  CASE_ORACLE="$OUT/case-$1-oracle.tsv"
  cp "$BASELINE" "$CASE_BASELINE"
  cp "$ORACLE" "$CASE_ORACLE"
}

commit_ledger() {
  local repo=$1
  git -C "$repo" add docs/COMPATIBILITY-LEDGER.tsv
  git -C "$repo" commit -q -m ledger-change
}

