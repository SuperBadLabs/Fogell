mutant_case() {
  local label=$1
  clone_case "mutant-$label"
  MUTANT="$CASE"
  MUTANT_CHECKER="$MUTANT/scripts/check-compatibility-regression.py"
  MUTANT_BASELINE="$CASE_BASELINE"
  MUTANT_ORACLE="$CASE_ORACLE"
}

commit_mutant() {
  local repo=$1 label=$2 before=$3
  local after
  after=$(sha256 "$repo/scripts/check-compatibility-regression.py")
  if [ "$before" = "$after" ]; then
    echo "  FAIL: $label mutation changed nothing"; FAILED=1; return 1
  fi
  git -C "$repo" add scripts/check-compatibility-regression.py
  git -C "$repo" commit -q -m "mutate $label"
}

