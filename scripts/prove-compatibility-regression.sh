expect_pass 'out-of-order unique corpus manifest' "$CASE" "$OUT/manifest-order-baseline.json" "$CASE_ORACLE"

expect_pass 'hostile inherited Git environment is ignored' "$REPO" "$BASELINE" "$ORACLE" \
  GIT_DIR=/hostile/git-dir GIT_WORK_TREE=/hostile/work-tree GIT_INDEX_FILE=/hostile/index \
  GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=core.ignoreCase GIT_CONFIG_VALUE_0=true

